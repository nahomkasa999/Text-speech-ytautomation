MAX_CHUNK = 4 * 1024 * 1024
# Encoded video arrives in ordered batches of whole frames (WebCodecs chunks).
MAX_BATCH_BYTES = 16 * 1024 * 1024
MAX_BATCH_FRAMES = 300
MAX_PATCH_RECORDS = 120
MAX_PATCH_FRAMES = 300
# Video the editor already compressed with WebCodecs: container fourcc per output format.
ENCODED_CODECS = {'mp4': ('h264', b'H264'), 'webm': ('vp9', b'VP90')}
DISK_RESERVE = 128 * 1024 * 1024
TERMINAL = {"completed", "cancelled", "failed"}
# Leave one core for the editor, which draws the frames while FFmpeg encodes them.
ENCODER_THREADS = max(2, min(16, (os.cpu_count() or 2) - 1))


def _video_maxrate(width, height, fps):
    return max(500_000, min(8_000_000, math.ceil(8_000_000 * width * height / (1920 * 1080) * fps / 30)))


def _video_bitrate(width, height, fps, container):
    """Average bitrate the editor's WebCodecs encoder targets, matching the x264/VP9 caps."""
    maxrate = _video_maxrate(width, height, fps)
    return maxrate if container == 'mp4' else min(4_000_000, maxrate)


def _ivf_header(fourcc, width, height, fps, frames):
    """IVF file header whose timestamps count in 1/fps units.

    Built with int.to_bytes: the 1.0.16 engine's frozen standard library lacks the binary packing module.
    """
    fields = ((0, 2), (32, 2))
    sizes = ((width, 2), (height, 2), (fps, 4), (1, 4), (frames, 4), (0, 4))
    return (b'DKIF' + b''.join(v.to_bytes(n, 'little') for v, n in fields) + fourcc
            + b''.join(v.to_bytes(n, 'little') for v, n in sizes))


def _split_chunks(data, count):
    """Split a batch of `count` frames, each `<u32 size><u8 flags><payload>`, flag 1 = keyframe."""
    view = memoryview(data)
    frames, pos = [], 0
    for _ in range(count):
        if pos + 5 > len(view):
            raise ValueError('Video chunk batch is truncated.')
        size, flags = int.from_bytes(view[pos:pos + 4], 'little'), view[pos + 4]
        pos += 5
        if not 0 < size <= len(view) - pos or flags & ~1:
            raise ValueError('Video chunk batch is malformed.')
        frames.append((bool(flags & 1), view[pos:pos + size]))
        pos += size
    if pos != len(view):
        raise ValueError('Video chunk batch has trailing bytes.')
    return frames


def _number(settings, key, default, low, high, integer=False):
    value = settings.get(key, default)
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise ValueError(f"Invalid {key}.")
    if not low <= value <= high or (integer and value != int(value)):
        raise ValueError(f"{key} must be between {low} and {high}.")
    return int(value) if integer else float(value)


def _audio_path(url):
    path = unquote(urlsplit(str(url)).path)
    root = Path(AUDIO_DIR).resolve()
    if not path.startswith('/audio/'):
        raise ValueError("Narration must be an audio file generated by this app.")
    candidate = (root / path[len('/audio/'):]).resolve()
    if candidate.parent != root or not candidate.is_file():
        raise ValueError("Narration audio was not found.")
    return str(candidate)


def _probe(executable, path):
    try:
        import soundfile
        info = soundfile.info(path)
        if info.frames > 0 and info.samplerate > 0 and info.channels in (1, 2):
            return info.frames / info.samplerate, info.samplerate, info.channels
    except (ImportError, RuntimeError):
        pass
    # Read only the container header. Do not decode a multi-hour narration.
    process = subprocess.Popen([executable, '-hide_banner', '-protocol_whitelist', 'file,pipe', '-i', path],
                               stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, creationflags=_creationflags())
    timer = threading.Timer(20, lambda: process.kill() if process.poll() is None else None)
    timer.start()
    try:
        metadata = process.stderr.read(65536).decode('utf-8', errors='replace')
    finally:
        timer.cancel()
        if process.poll() is None:
            process.kill()
        process.wait()
        process.stderr.close()
    duration = re.search(r'Duration: (\d+):(\d+):(\d+(?:\.\d+)?)', metadata)
    sample_rate = re.search(r'Audio:.*?,\s*(\d+) Hz', metadata)
    if not duration or not sample_rate:
        raise ValueError("FFmpeg could not read the narration audio duration and sample rate.")
    hours, minutes, seconds = map(float, duration.groups())
    audio_line = re.search(r'Audio:.*', metadata).group(0)
    # FFmpeg prints "mono" for a known layout, "1 channels" for e.g. a plain mono WAV.
    channels = 1 if re.search(r',\s*(?:mono|1 channels)\s*,', audio_line) else 2
    return hours * 3600 + minutes * 60 + seconds, int(sample_rate.group(1)), channels


def _creationflags():
    return subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0


def _lock(handle):
    """Take the journal record's exclusive lock without waiting.

    The OS releases it when the owner exits, in any PID namespace, so a held
    lock is the only reliable sign that an export is still running.
    """
    try:
        handle.seek(0)
        if os.name == 'nt':
            msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        return True
    except OSError:
        return False


@dataclass
class ExportJob:
    id: str
    target: Path
    partial: Path
    music: Path
    audio: str
    executable: str
    width: int
    height: int
    fps: int
    duration: float
    total_frames: int
    settings: dict
    sample_rate: int
    channels: int
    video: str = 'raw'
    encoder: str | None = None
    stage: str = 'prepared'
    frames: int = 0
    music_bytes: int = 0
    encoded_seconds: float = 0
    error: str = ''
    started: float = field(default_factory=time.monotonic)
    touched: float = field(default_factory=time.monotonic)
    process: object = None
    picture: object = None
    claim: object = None
    logs: deque = field(default_factory=lambda: deque(maxlen=24))
    lock: object = field(default_factory=threading.RLock)
    operation: object = field(default_factory=threading.Lock)
    transport: object = field(default_factory=threading.Lock)

    def status(self):
        with self.lock:
            elapsed = max(0, time.monotonic() - self.started)
            speed = self.encoded_seconds / elapsed if elapsed else 0
            return dict(ok=True, id=self.id, stage=self.stage, frames=self.frames,
                        progress=min(1, self.frames / self.total_frames), elapsed_seconds=elapsed,
                        speed=speed, eta_seconds=(max(0, self.duration-self.encoded_seconds)/speed
                        if speed and self.stage == 'encoding' else (0 if self.stage == 'completed' else None)),
                        encoded_seconds=self.encoded_seconds, error=self.error, video_encoding=self.video, video_encoder=self.encoder,
                        path=str(self.target) if self.stage == 'completed' else None)


class ExportManager:
    def __init__(self, lease_seconds=180, journal_dir=None):
        self.jobs = {}
        self.lock = threading.Lock()
        self.lease_seconds = lease_seconds
        self.closed = threading.Event()
        self.reaper = None
        self.journal_dir = Path(journal_dir or Path(APP_DATA_DIR) / 'outputs' / 'export-jobs')
        self.journal_dir.mkdir(parents=True, exist_ok=True)
        self._recover()

    def _recover(self):
        for record in self.journal_dir.glob('*.json'):
            if not re.fullmatch('[0-9a-f]{32}', record.stem):
                continue
            try:
                with record.open('r+b') as claim:
                    if not _lock(claim):
                        continue
                    target = Path(json.loads(claim.read())['target'])
                    if not target.is_absolute():
                        continue
                    for suffix in ('partial', 'music'):
                        (target.parent / f'.{target.name}.{record.stem}.{suffix}').unlink(missing_ok=True)
                record.unlink()
            except (OSError, ValueError, KeyError, TypeError):
                continue

    def _forget(self, job):
        try:
            if not job.partial.exists() and not job.music.exists():
                job.claim.close()
                (self.journal_dir / f'{job.id}.json').unlink(missing_ok=True)
        except OSError:
            pass

    def prepare(self, target, settings):
        with self.lock:
            if self.closed.is_set():
                raise ValueError('The exporter is shutting down.')
            if any(j.stage not in TERMINAL for j in self.jobs.values()):
                raise ValueError('Another video export is already running.')
            width = _number(settings, 'width', 1280, 16, 1920, True)
            height = _number(settings, 'height', 720, 16, 1920, True)
            if width % 2 or height % 2 or width * height > 1920 * 1080:
                raise ValueError('Use even video dimensions of at most 1920 × 1080 pixels.')
            fps = _number(settings, 'fps', 24, 1, 60, True)
            clean = dict(speed=_number(settings, 'speed', 1, .25, 4),
                         volume=_number(settings, 'volume', 1, 0, 2),
                         music_volume=_number(settings, 'music_volume', .15, 0, 2),
                         format=settings.get('format', 'mp4'),
                         preserve_pitch=settings.get('preserve_pitch', True))
            if clean['format'] not in ('mp4', 'webm') or not isinstance(clean['preserve_pitch'], bool):
                raise ValueError('Invalid export format or pitch setting.')
            clean['preset'] = settings.get('cpu_preset', 'veryfast')
            if clean['preset'] not in ('veryfast', 'superfast', 'ultrafast'):
                raise ValueError('Invalid CPU encoding preset.')
            video = settings.get('video_encoding', 'raw')
            if video not in ('raw', 'webcodecs'):
                raise ValueError('Invalid video encoding setting.')
            executable = validate_ffmpeg()
            audio = _audio_path(settings.get('audio_url', ''))
            raw_duration, sample_rate, channels = _probe(executable, audio)
            duration = raw_duration / clean['speed']
            if not 0 < duration <= 48 * 3600:
                raise ValueError('Narration must be between zero and 48 hours after speed adjustment.')
            target = Path(target).absolute()
            free = shutil.disk_usage(target.parent).free
            maxrate = _video_maxrate(width, height, fps)
            required = math.ceil(duration * (maxrate + 192_000) / 8 * 1.15) + DISK_RESERVE
            if free < required:
                raise ValueError(f'Not enough space on the destination disk. Allow {required / 1024**3:.1f} GB.')
            token = uuid.uuid4().hex
            partial = target.parent / f'.{target.name}.{token}.partial'
            music = target.parent / f'.{target.name}.{token}.music'
            claim = (self.journal_dir / f'{token}.json').open('x+b')
            if not _lock(claim):
                claim.close()
                raise OSError('Could not reserve the export journal. Try again.')
            claim.write(json.dumps({'target': str(target)}).encode())
            claim.flush()
            with partial.open('xb'):
                pass
            job = ExportJob(token, target, partial, music, audio, executable, width, height, fps,
                            duration, math.ceil(duration * fps), clean, sample_rate, channels,
                            video=video, claim=claim)
            self.jobs[token] = job
            while len(self.jobs) > 8:
                self.jobs.pop(next(iter(self.jobs)))
            if self.reaper is None:
                self.reaper = threading.Thread(target=self._reap, daemon=True)
                self.reaper.start()
            return dict(ok=True, id=token, width=width, height=height, fps=fps, duration=duration,
                        total_frames=job.total_frames, free_bytes=free, video_encoding=video,
                        video_codec=ENCODED_CODECS[clean['format']][0],
                        video_bitrate=_video_bitrate(width, height, fps, clean['format']),
                        keyframe_interval=fps * 2, max_batch_bytes=MAX_BATCH_BYTES, max_batch_frames=MAX_BATCH_FRAMES,
                        max_patch_batch_bytes=MAX_BATCH_BYTES, max_patch_batch_frames=MAX_PATCH_FRAMES,
                        max_patch_batch_records=MAX_PATCH_RECORDS)

    def get(self, token):
        with self.lock:
            job = self.jobs.get(token)
        if job is None:
            raise ValueError('Video export was not found.')
        return job

    def _reap(self):
        while not self.closed.wait(5):
            with self.lock:
                jobs = list(self.jobs.values())
            for job in jobs:
                if job.stage not in TERMINAL and time.monotonic() - job.touched > self.lease_seconds:
                    self.cancel(job.id, 'Export stopped because the editor disconnected.')
                elif (job.stage == 'encoding' and job.process.poll() is not None
                      and (job.process.returncode != 0 or job.frames < job.total_frames)):
                    self.cancel(job.id, 'FFmpeg stopped unexpectedly. ' + ' '.join(job.logs)[-2000:])

    def _disk_check(self, job):
        if shutil.disk_usage(job.target.parent).free < DISK_RESERVE:
            raise OSError('The destination disk is nearly full. Free some space and export again.')

    def upload_music(self, token, offset, data):
        job = self.get(token)
        with job.operation:
            with job.lock:
                if job.stage != 'prepared' or offset != job.music_bytes:
                    raise ValueError('Music upload is out of order or encoding has already started.')
                if not 0 < len(data) <= MAX_CHUNK or offset + len(data) > 512 * 1024 * 1024:
                    raise ValueError('Music must be at most 512 MB, uploaded in chunks of at most 4 MB.')
                self._disk_check(job)
                with job.music.open('ab') as output:
                    output.write(data)
                job.music_bytes += len(data)
                job.touched = time.monotonic()
        return job.status()

    def _command(self, job):
        s = job.settings
        encoded = job.video != 'raw'
        command = [job.executable, '-hide_banner', '-loglevel', 'warning', '-nostdin', '-y', '-filter_complex_threads', '1']
        if encoded:
            # IVF frame headers carry each frame's timestamp, so the copied stream is exactly
            # constant frame rate. Raw H.264 has no timestamps of its own.
            command += ['-f', 'ivf', '-i', 'pipe:0']
        else:
            command += ['-threads', '2', '-f', 'rawvideo', '-pix_fmt', 'yuv420p',
                        '-s', f'{job.width}x{job.height}', '-r', str(job.fps), '-i', 'pipe:0']
        command += ['-threads', '2', '-protocol_whitelist', 'file,pipe', '-i', job.audio]
        if job.music_bytes:
            command += ['-stream_loop', '-1', '-threads', '2', '-protocol_whitelist', 'file,pipe', '-i', str(job.music)]
        speed = s['speed']
        if s['preserve_pitch']:
            factors = []
            while speed > 2:
                factors.append('atempo=2')
                speed /= 2
            while speed < .5:
                factors.append('atempo=0.5')
                speed /= .5
            factors.append(f'atempo={speed}')
            tempo = ','.join(factors)
        else:
            tempo = f'asetrate={job.sample_rate * speed},aresample=48000'
        layout = 'mono' if job.channels == 1 else 'stereo'
        filters = f'[1:a:0]{tempo},aresample=48000,aformat=channel_layouts={layout},volume={s["volume"]},apad[n]'
        if job.music_bytes:
            _, _, music_channels = _probe(job.executable, str(job.music))
            downmix = 'pan=mono|c0=0.5*c0+0.5*c1,' if job.channels == 1 and music_channels == 2 else ''
            filters += f';[2:a:0]{downmix}aresample=48000,aformat=channel_layouts={layout},volume={s["music_volume"]}[m];[n][m]amix=inputs=2:duration=first:normalize=0,aeval=clip(val(0)\\,-1\\,1)'
            if job.channels == 2:
                filters += '|clip(val(1)\\,-1\\,1)'
            filters += f',aformat=channel_layouts={layout}[a]'
        else:
            filters += ';[n]anull[a]'
        command += ['-filter_complex', filters, '-map', '0:v:0', '-map', '[a]', '-frames:v', str(job.total_frames), '-t', str(job.duration),
                    '-threads', str(ENCODER_THREADS), '-max_muxing_queue_size', '128']
        if encoded:
            command += ['-c:v', 'copy']
            if s['format'] == 'mp4':
                # The default shifts every video frame after the first by the AAC priming delay.
                command += ['-avoid_negative_ts', 'make_non_negative', '-c:a', 'aac', '-b:a', '192k',
                            '-movflags', '+frag_keyframe+empty_moov+default_base_moof+skip_trailer', '-f', 'mp4']
            else:
                command += ['-c:a', 'libopus', '-b:a', '160k', '-cluster_time_limit', '2000', '-live', '1', '-f', 'webm']
            return command + ['-progress', 'pipe:1', '-nostats', str(job.partial)]
        command += ['-colorspace', 'smpte170m', '-color_range', 'tv']
        if s['format'] == 'mp4':
            bitrate = _video_maxrate(job.width, job.height, job.fps)
            if job.encoder and job.encoder != 'libx264':
                command += hardware_encoder_options(job.encoder, bitrate, job.fps)
            else:
                command += ['-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-preset', s['preset'],
                            '-bf', '0', '-crf', '20', '-maxrate', str(bitrate), '-bufsize', str(bitrate),
                            '-g', str(job.fps * 2)]
            command += ['-c:a', 'aac', '-b:a', '192k',
                        '-movflags', '+frag_keyframe+empty_moov+default_base_moof+skip_trailer', '-f', 'mp4']
        else:
            command += ['-pix_fmt', 'yuv420p', '-c:v', 'libvpx-vp9', '-deadline', 'realtime', '-cpu-used', '6', '-row-mt', '1',
                        '-lag-in-frames', '0', '-b:v', str(min(4_000_000, _video_maxrate(job.width, job.height, job.fps))),
                        '-maxrate', str(_video_maxrate(job.width, job.height, job.fps)),
                        '-bufsize', str(_video_maxrate(job.width, job.height, job.fps)),
                        '-g', str(job.fps * 2), '-c:a', 'libopus', '-b:a', '160k',
                        '-cluster_time_limit', '2000', '-live', '1', '-f', 'webm']
        return command + ['-progress', 'pipe:1', '-nostats', str(job.partial)]

    def start(self, token, video=None):
        """Start FFmpeg. `video='raw'` lets the editor fall back to raw frames if its encoder failed."""
        job = self.get(token)
        with job.operation:
            encoder = (select_video_encoder(job.executable, job.width, job.height, job.fps)
                       if (video or job.video) == 'raw' and job.settings['format'] == 'mp4' else None)
            with job.lock:
                if job.stage != 'prepared':
                    raise ValueError('This export has already started or stopped.')
                if video not in (None, 'raw', job.video):
                    raise ValueError('Invalid video encoding for this export.')
                if video is not None:
                    job.video = video
                try:
                    self._disk_check(job)
                    job.encoder = encoder if job.video == 'raw' else None
                    job.process = subprocess.Popen(self._command(job), stdin=subprocess.PIPE,
                        stdout=subprocess.PIPE, stderr=subprocess.PIPE, bufsize=0, creationflags=_creationflags())
                    if job.video != 'raw':
                        fourcc = ENCODED_CODECS[job.settings['format']][1]
                        self._write(job, _ivf_header(fourcc, job.width, job.height, job.fps, job.total_frames))
                    job.stage = 'encoding'
                    job.started = job.touched = time.monotonic()
                except Exception as exc:
                    self.cancel(token, str(exc))
                    raise
            threading.Thread(target=self._read_progress, args=(job,), daemon=True).start()
            threading.Thread(target=self._read_errors, args=(job,), daemon=True).start()
        return job.status()

    def _read_progress(self, job):
        for line in iter(job.process.stdout.readline, b''):
            if line.startswith(b'out_time_us='):
                try:
                    job.encoded_seconds = min(job.duration, int(line.partition(b'=')[2]) / 1_000_000)
                except ValueError:
                    pass
        job.process.stdout.close()

    def _read_errors(self, job):
        for line in iter(lambda: job.process.stderr.readline(4096), b''):
            job.logs.append(line.decode('utf-8', errors='replace').strip()[:1000])
        job.process.stderr.close()

    def frame(self, token, index, repeat, data, box=None):
        job = self.get(token)
        return self._frames(job, index, [(box or (0, 0, job.width, job.height), repeat, data)])

    def frames(self, token, index, count, data):
        if not 1 <= count <= MAX_PATCH_RECORDS or len(data) > MAX_BATCH_BYTES:
            raise ValueError('Invalid video patch batch size.')
        body = memoryview(data)
        records = []
        offset = 0
        for _ in range(count):
            if offset + 24 > len(body):
                raise ValueError('Video patch batch is truncated.')
            fields = [int.from_bytes(body[pos:pos + 4], 'little') for pos in range(offset, offset + 24, 4)]
            offset += 24
            x, y, width, height, repeat, size = fields
            if offset + size > len(body):
                raise ValueError('Video patch batch is truncated.')
            records.append(((x, y, width, height), repeat, body[offset:offset + size]))
            offset += size
        if offset != len(body):
            raise ValueError('Video patch batch has trailing bytes.')
        return self._frames(self.get(token), index, records)

    def _frames(self, job, index, records):
        with job.operation:
            with job.lock:
                if job.stage != 'encoding' or index != job.frames:
                    raise ValueError('Video frame is out of order or export is not encoding.')
                if job.video != 'raw':
                    raise ValueError('This export expects encoded video chunks, not raw frames.')
                frames = sum(repeat for _, repeat, _ in records)
                if frames > MAX_PATCH_FRAMES or index + frames > job.total_frames:
                    raise ValueError('Invalid repeated frame count.')
                whole_box = (0, 0, job.width, job.height)
                for offset, (box, repeat, data) in enumerate(records):
                    x, y, width, height = box
                    if repeat < 1:
                        raise ValueError('Invalid repeated frame count.')
                    if not (0 <= x < x + width <= job.width and 0 <= y < y + height <= job.height):
                        raise ValueError('Video frame box is outside the picture.')
                    if len(data) != width * height * 4:
                        raise ValueError('Video frame has an incorrect byte length.')
                    if offset == 0 and index == 0 and box != whole_box:
                        raise ValueError('The first video frame must cover the whole picture.')
                job.touched = time.monotonic()
            try:
                self._disk_check(job)
                for box, repeat, data in records:
                    if job.stage != 'encoding':
                        raise ValueError('Export was cancelled.')
                    picture = self._patch_picture(job, box, data)
                    for _ in range(repeat):
                        if job.stage != 'encoding':
                            raise ValueError('Export was cancelled.')
                        self._write(job, picture)
                        job.frames += 1
                        job.touched = time.monotonic()
            except Exception as exc:
                error = str(exc)
                if job.logs:
                    error += ' ' + ' '.join(job.logs)[-2000:]
                self.cancel(job.id, error)
                raise ValueError(error) from exc
        return job.status()

    @staticmethod
    def _patch_picture(job, box, data):
        if job.picture is None:
            job.picture = ExportPicture(job.width, job.height)
        return job.picture.update(data, box)

    @staticmethod
    def _write(job, data):
        remaining = memoryview(data)
        while remaining:
            written = job.process.stdin.write(remaining)
            if not written:
                raise BrokenPipeError('FFmpeg closed the input pipe.')
            remaining = remaining[written:]

    def chunks(self, token, index, count, data):
        """Mux the next `count` encoded frames, starting at frame `index`, into the video.

        Each frame becomes one IVF frame whose timestamp is its frame number, so
        the output keeps exactly one frame per 1/fps whatever the encoder did.
        """
        job = self.get(token)
        with job.operation:
            with job.lock:
                if job.stage != 'encoding' or index != job.frames:
                    raise ValueError('Video chunk is out of order or export is not encoding.')
                if job.video == 'raw':
                    raise ValueError('This export expects raw video frames, not encoded chunks.')
                if not 1 <= count <= MAX_BATCH_FRAMES or index + count > job.total_frames:
                    raise ValueError('Invalid video chunk count.')
                if len(data) > MAX_BATCH_BYTES:
                    raise ValueError('Video chunk batch is too large.')
                frames = _split_chunks(data, count)
                if index == 0 and not frames[0][0]:
                    raise ValueError('The first video chunk must be a keyframe.')
                job.touched = time.monotonic()
            try:
                self._disk_check(job)
                for offset, (_, payload) in enumerate(frames):
                    if job.stage != 'encoding':
                        raise ValueError('Export was cancelled.')
                    # IVF frame header: payload size, then the timestamp in 1/fps units.
                    self._write(job, len(payload).to_bytes(4, 'little') + (index + offset).to_bytes(8, 'little'))
                    self._write(job, payload)
                    job.frames += 1
                    job.touched = time.monotonic()
            except Exception as exc:
                error = str(exc)
                if job.logs:
                    error += ' ' + ' '.join(job.logs)[-2000:]
                self.cancel(token, error)
                raise ValueError(error) from exc
        return job.status()

    def finish(self, token):
        job = self.get(token)
        with job.operation:
            with job.lock:
                if job.stage != 'encoding' or job.frames != job.total_frames:
                    raise ValueError('All video frames must be supplied before finishing.')
                job.stage = 'finishing'
                job.touched = time.monotonic()
            try:
                job.process.stdin.close()
                result = job.process.wait(timeout=120)
                with job.lock:
                    if job.stage != 'finishing':
                        raise ValueError(job.error or 'Export was cancelled.')
                    if result != 0 or not job.partial.stat().st_size:
                        raise ValueError('FFmpeg could not finish the video. ' + ' '.join(job.logs)[-2000:])
                    self._disk_check(job)
                    os.replace(job.partial, job.target)
                    job.stage = 'completed'
                    job.picture = None
                    job.encoded_seconds = job.duration
                    try:
                        job.music.unlink(missing_ok=True)
                    except OSError:
                        pass
                    self._forget(job)
            except Exception as exc:
                self.cancel(token, str(exc))
                raise ValueError(str(exc)) from exc
        return job.status()

    def cancel(self, token, error=''):
        job = self.get(token)
        with job.lock:
            if job.stage in TERMINAL:
                return job.status()
            job.stage = 'failed' if error else 'cancelled'
            job.error = error
            job.picture = None
            process = job.process
        # This never takes the pipe writer's lock. Killing FFmpeg unblocks writes.
        if process is not None:
            if process.poll() is None:
                try:
                    process.kill()
                except ProcessLookupError:
                    pass
            process.wait(timeout=10)
            if process.stdin and not process.stdin.closed:
                process.stdin.close()
        for path in (job.partial, job.music):
            try:
                path.unlink(missing_ok=True)
            except OSError:
                pass
        self._forget(job)
        return job.status()

    def shutdown(self):
        self.closed.set()
        with self.lock:
            jobs = list(self.jobs.values())
        for job in jobs:
            self.cancel(job.id)


